package com.feraxhp.gallery.model

import androidx.compose.ui.geometry.Rect
import androidx.compose.ui.graphics.Matrix
import androidx.compose.ui.graphics.vector.ImageVector

// Represents a category of editing tools (e.g., Transform, Adjust)
data class Category(
    val id: String,
    val name: String,
    val icon: ImageVector,
    val tools: List<Tool>
)

// Represents an individual editing tool within a category
data class Tool(
    val id: String,
    val name: String,
    val icon: ImageVector,
    val explanation: String,
    val exampleModel: Any? = null, // Supports Coil 3 ImageRequest, URL or DrawableResource (GIF/image)
    val onApply: (ToolParams) -> EditOperation
)

// Parameters generated by interactive UI tools
sealed interface ToolParams {
    data class Crop(val cropRect: Rect, val aspectRatio: Float?) : ToolParams
    data class Rotate(val degrees: Float) : ToolParams
    data class Flip(val horizontal: Boolean, val vertical: Boolean) : ToolParams
    data class Straighten(val angle: Float) : ToolParams
}

// Immutable edit operations applied sequentially
sealed interface EditOperation {
    val id: String
    
    // Applies this operation's mathematical transformation to the provided Matrix
    fun apply(matrix: Matrix): Matrix
    
    data class CropOp(val bounds: Rect, val ratio: Float?) : EditOperation {
        override val id: String = "crop"
        override fun apply(matrix: Matrix): Matrix = matrix // Transform crop canvas bounds handled elsewhere
    }
    
    data class RotateStepOp(val degrees: Float) : EditOperation {
        override val id: String = "rotate_90"
        override fun apply(matrix: Matrix): Matrix = matrix.apply { rotateZ(degrees) }
    }
    
    data class FlipOp(val flipH: Boolean, val flipV: Boolean) : EditOperation {
        override val id: String = "flip"
        override fun apply(matrix: Matrix): Matrix = matrix.apply { 
            scale(if (flipH) -1f else 1f, if (flipV) -1f else 1f) 
        }
    }
    
    data class StraightenOp(val angle: Float) : EditOperation {
        override val id: String = "straighten"
        override fun apply(matrix: Matrix): Matrix = matrix.apply { rotateZ(angle) }
    }
}
